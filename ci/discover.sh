#!/bin/bash
# Works out what is missing on the GitHub releases and writes the child pipeline that builds it.
#   wanted  = every Unraid kernel >= min_kernel with an ich777 kernel tree
#             x every cmpunlocker tag in versions.json
#             x the newest drivers_per_tag drivers that tag supports (its driver/VERSION) and that have a
#               stock unraid-nvidia-driver package on any kernel (the userspace source)
#             x every profile
#   missing = wanted minus what the kernel's manifest.json already lists
# FORCE_KVER=<kver> rebuilds everything for that one kernel.
# Usage: ci/discover.sh <child-pipeline.yml>      Needs: gh (GH_TOKEN, GH_REPO), jq, curl.
set -euo pipefail
YML="${1:?output file}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

MIN="$(jq -r .min_kernel versions.json)"
PER_TAG="$(jq -r .drivers_per_tag versions.json)"
mapfile -t REFS < <(jq -r '.cmpunlocker[]' versions.json)
mapfile -t PROFILES < <(jq -r '.profiles[]' versions.json)
STOCK="$(gh api --paginate repos/unraid/unraid-nvidia-driver/releases --jq '.[].assets[].name')"

# "<driver> <ref>" pairs we build
: > "$WORK/pairs"
for ref in "${REFS[@]}"; do
  for drv in $(curl -fsSL "https://raw.githubusercontent.com/amoghmunikote/cmpunlocker/refs/tags/$ref/driver/VERSION" \
               | grep -E '^[0-9]+\.[0-9]+\.[0-9]+$' | sort -rV); do
    if ! grep -qE "^nvidia-${drv//./\\.}-.*-Unraid-1\.txz$" <<<"$STOCK"; then
      echo "notice: driver $drv (cmpunlocker $ref) has no stock unraid-nvidia-driver package anywhere, skipped" >&2
    elif [ "$(grep -c " $ref\$" "$WORK/pairs")" -lt "$PER_TAG" ]; then
      echo "$drv $ref" >> "$WORK/pairs"
    fi
  done
done

if [ -n "${FORCE_KVER:-}" ]; then
  KERNELS="$FORCE_KVER"
else
  KERNELS="$(gh api --paginate repos/ich777/unraid_kernel/releases --jq '.[].tag_name' \
    | grep -E '^[0-9]+\.[0-9]+\.[0-9]+-Unraid$' || true)"
fi

: > "$WORK/userspace"
: > "$WORK/jobs"
for kver in $KERNELS; do
  [ "$(printf '%s\n%s\n' "$MIN" "${kver%%-*}" | sort -V | head -1)" = "$MIN" ] || continue
  have=""
  [ -n "${FORCE_KVER:-}" ] || have="$(gh release download "$kver" -p manifest.json -O - 2>/dev/null \
    | jq -r '.packages[] | "\(.driver) \(.cmpunlocker) \(.profile)"' || true)"
  builds=""
  while read -r drv ref; do
    for profile in "${PROFILES[@]}"; do
      grep -qxF "$drv $ref $profile" <<<"$have" && continue
      builds+="      KVER=$kver DRV=$drv CMPUNLOCKER_REF=$ref PROFILE=$profile bash ci/build.sh && ok=\$((ok+1)) || failed=\$((failed+1))"$'\n'
      echo "$drv" >> "$WORK/userspace"
    done
  done < "$WORK/pairs"
  [ -n "$builds" ] || continue
  gcc="$(gh release view "$kver" --repo ich777/unraid_kernel --json body --jq .body || true)"
  gcc="$(grep -oE 'gcc_[0-9.]+' <<<"$gcc" || true)"; gcc="${gcc%%$'\n'*}"
  if [ -z "$gcc" ]; then
    echo "warning: $kver: no gcc version in the ich777/unraid_kernel release body, skipped" >&2
    continue
  fi
  echo "$kver: $(grep -c . <<<"$builds") package(s) to build with $gcc" >&2
  cat >> "$WORK/jobs" <<EOF

build:$kver:
  stage: build
  image:
    name: ghcr.io/ich777/unraid_kernel:$gcc
    entrypoint: [""]    # the image's own entrypoint starts sshd and waits forever; ci/build.sh fetches the tree
  script:
    - |
      ok=0 failed=0
$builds      echo "built \$ok, failed \$failed"
      [ "\$ok" -gt 0 ] || exit 1
      [ "\$failed" = 0 ] || exit 3
  allow_failure:
    exit_codes: [3]
  artifacts:
    when: always
    paths: [out/$kver/]
    expire_in: 1 week

publish:$kver:
  extends: .gh
  stage: publish
  needs: ["build:$kver"]
  script:
    - bash ci/publish.sh $kver
EOF
done

# The generated pipeline: userspace releases first, then per kernel build -> publish. One failed
# combination does not hold back the others: the build job continues and, if anything was built, ends
# with exit 3 (an allowed failure, shown as a warning) so publish still runs for what was built.
{
  cat <<'EOF'
# generated by ci/discover.sh
stages: [userspace, build, publish]

default:
  tags: [linux]

.gh:
  image: alpine:3.22
  before_script:
    - apk add --no-cache bash coreutils curl jq tar xz github-cli
EOF
  for drv in $(sort -u "$WORK/userspace"); do
    cat <<EOF

userspace:$drv:
  extends: .gh
  stage: userspace
  script:
    - bash ci/userspace.sh $drv
EOF
  done
  if [ -s "$WORK/jobs" ]; then
    cat "$WORK/jobs"
  else
    printf '\nnothing-to-do:\n  stage: build\n  image: alpine:3.22\n  script: [echo "All wanted packages are published."]\n'
  fi
} > "$YML"
echo "wrote $YML" >&2
